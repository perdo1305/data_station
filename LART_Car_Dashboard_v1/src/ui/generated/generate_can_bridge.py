import os
import re
import glob
import cantools
import cantools.subparsers.generate_c_source as gen

_UNSAFE = re.compile(r'[^a-zA-Z0-9_]')

def _ros_name(raw: str) -> str:
    """Sanitize a name to a valid ROS topic segment (using val_ if starting with digit)."""
    slug = _UNSAFE.sub('_', raw).strip('_').lower()
    if slug and slug[0].isdigit():
        slug = 'val_' + slug
    return slug

def _to_c_name(raw: str) -> str:
    """Convert a name to the snake-case C name used by cantools generate_c_source."""
    s = gen.camel_to_snake_case(raw)
    if s and s[0].isdigit():
        s = '_' + s
    s = re.sub(r'[^a-zA-Z0-9_]', '_', s)
    return s

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    dbc_dir = os.path.abspath(os.path.join(script_dir, "../../../../dbc_signals"))
    
    db_configs = [
        {"name": "data_t26", "file": "data_t26.dbc"},
        {"name": "powertrain_t26", "file": "powertrain_t26.dbc"},
        {"name": "autonomous_t26", "file": "autonomous_t26.dbc"}
    ]
    
    # 1. Read the DBC databases
    databases = []
    for cfg in db_configs:
        dbc_path = os.path.join(dbc_dir, cfg["file"])
        db = cantools.database.load_file(dbc_path)
        databases.append({"db_name": cfg["name"], "db": db})
    
    # 2. Collect all messages that have signals
    messages_to_decode = []
    for db_info in databases:
        db_name = db_info["db_name"]
        for msg in db_info["db"].messages:
            if not msg.signals:
                continue
            messages_to_decode.append({
                "db_name": db_name,
                "msg": msg,
                "frame_id": msg.frame_id,
                "msg_name": msg.name,
                "msg_slug": _ros_name(msg.name),
                "msg_c_name": _to_c_name(msg.name)
            })
            
    # Sort messages by frame_id
    messages_to_decode.sort(key=lambda x: x["frame_id"])
    
    # 3. Generate Header File: can_bridge_impl.hpp
    hpp_lines = [
        "// Auto-generated by generate_can_bridge.py. Do not edit.",
        "#ifndef CAN_BRIDGE_IMPL_HPP",
        "#define CAN_BRIDGE_IMPL_HPP",
        "",
        "#include <rclcpp/rclcpp.hpp>",
        "#include <std_msgs/msg/float32.hpp>",
        "#include <memory>",
        "",
        "// Include the cantools-generated C headers",
        '#include "data_t26.h"',
        '#include "powertrain_t26.h"',
        '#include "autonomous_t26.h"',
        "",
        "class CanBridgeImpl {",
        "public:",
        "    explicit CanBridgeImpl(rclcpp::Node* node);",
        "    ~CanBridgeImpl() = default;",
        "",
        "    /**",
        "     * @brief Dispatch raw CAN frame payload to unpacked DBC decoding and publish.",
        "     * @return true if the frame matched a DBC ID and was processed, false otherwise.",
        "     */",
        "    bool handle_frame(uint32_t can_id, const uint8_t* data, size_t dlc);",
        "",
        "private:",
        "    rclcpp::Node* node_;",
        ""
    ]
    
    # Add publisher declarations
    for m_info in messages_to_decode:
        db_name = m_info["db_name"]
        msg_slug = m_info["msg_slug"]
        hpp_lines.append(f"    // Publishers for message: {m_info['msg_name']} (0x{m_info['frame_id']:X})")
        for sig in m_info["msg"].signals:
            sig_slug = _ros_name(sig.name)
            pub_name = f"pub_{db_name}_{msg_slug}_{sig_slug}"
            hpp_lines.append(f"    rclcpp::Publisher<std_msgs::msg::Float32>::SharedPtr {pub_name};")
        hpp_lines.append("")
        
    hpp_lines.extend([
        "};",
        "",
        "#endif // CAN_BRIDGE_IMPL_HPP"
    ])
    
    hpp_path = os.path.join(script_dir, "can_bridge_impl.hpp")
    with open(hpp_path, "w") as f:
        f.write("\n".join(hpp_lines) + "\n")
    print(f"Generated: {hpp_path}")
    
    # 4. Generate Source File: can_bridge_impl.cpp
    cpp_lines = [
        "// Auto-generated by generate_can_bridge.py. Do not edit.",
        '#include "can_bridge_impl.hpp"',
        "",
        "CanBridgeImpl::CanBridgeImpl(rclcpp::Node* node) : node_(node) {",
        "    auto sensor_qos = rclcpp::QoS(10).best_effort();",
        ""
    ]
    
    # Initialize publishers
    for m_info in messages_to_decode:
        db_name = m_info["db_name"]
        msg_slug = m_info["msg_slug"]
        for sig in m_info["msg"].signals:
            sig_slug = _ros_name(sig.name)
            pub_name = f"pub_{db_name}_{msg_slug}_{sig_slug}"
            topic = f"/can/dbc/{msg_slug}/{sig_slug}"
            cpp_lines.append(f'    {pub_name} = node_->create_publisher<std_msgs::msg::Float32>("{topic}", sensor_qos);')
    
    cpp_lines.extend([
        "}",
        "",
        "bool CanBridgeImpl::handle_frame(uint32_t can_id, const uint8_t* data, size_t dlc) {",
        "    (void)data;",
        "    (void)dlc;",
        "    switch (can_id) {"
    ])
    
    # Group messages by frame_id to avoid duplicate switch-case labels
    grouped_messages = {}
    for m_info in messages_to_decode:
        fid = m_info["frame_id"]
        if fid not in grouped_messages:
            grouped_messages[fid] = []
        grouped_messages[fid].append(m_info)
        
    # Add handle_frame switch case dispatch block
    for fid in sorted(grouped_messages.keys()):
        cpp_lines.append(f"        case {fid}u: {{")
        
        for m_info in grouped_messages[fid]:
            db_name = m_info["db_name"]
            msg_c_name = m_info["msg_c_name"]
            msg_slug = m_info["msg_slug"]
            
            cpp_lines.extend([
                f"            {{",
                f"                struct {db_name}_{msg_c_name}_t decoded = {{}};",
                f"                if ({db_name}_{msg_c_name}_unpack(&decoded, data, dlc) == 0) {{",
                f"                    std_msgs::msg::Float32 out;"
            ])
            
            for sig in m_info["msg"].signals:
                sig_slug = _ros_name(sig.name)
                sig_c_name = _to_c_name(sig.name)
                pub_name = f"pub_{db_name}_{msg_slug}_{sig_slug}"
                
                # Form the C decode function
                decode_fn = f"{db_name}_{msg_c_name}_{sig_c_name}_decode"
                
                cpp_lines.extend([
                    f"                    out.data = {decode_fn}(decoded.{sig_c_name});",
                    f"                    {pub_name}->publish(out);"
                ])
                
            cpp_lines.extend([
                f"                }}",
                f"            }}"
            ])
            
        cpp_lines.extend([
            f"            return true;",
            f"        }}"
        ])
        
    cpp_lines.extend([
        "        default:",
        "            return false;",
        "    }",
        "}"
    ])
    
    cpp_path = os.path.join(script_dir, "can_bridge_impl.cpp")
    with open(cpp_path, "w") as f:
        f.write("\n".join(cpp_lines) + "\n")
    print(f"Generated: {cpp_path}")

if __name__ == "__main__":
    main()
